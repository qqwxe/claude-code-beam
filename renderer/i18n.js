function getCurrentLanguage() {
  return localStorage.getItem('cst_lang') || 'en';
}

function getDict() {
  const lang = getCurrentLanguage();
  return translations[lang] || translations.en;
}

function t(key, ...args) {
  const dict = getDict();
  let entry = dict[key];
  if (entry === undefined) entry = translations.en[key];
  if (typeof entry === 'function') return entry(...args);
  return entry;
}

function tSteps() {
  const dict = getDict();
  return dict.tutorialSteps || translations.en.tutorialSteps;
}

function applyStaticTranslations() {
  document.querySelectorAll('[data-i18n]').forEach((el) => {
    el.textContent = t(el.getAttribute('data-i18n'));
  });
  document.querySelectorAll('[data-i18n-placeholder]').forEach((el) => {
    el.placeholder = t(el.getAttribute('data-i18n-placeholder'));
  });
  document.querySelectorAll('[data-i18n-title]').forEach((el) => {
    el.title = t(el.getAttribute('data-i18n-title'));
  });
  document.documentElement.lang = getCurrentLanguage();
  updateSelectedCountText();
}

function updateSelectedCountText() {
  const el = document.getElementById('selected-count');
  if (!el) return;
  const n = (window.__cstSelectedCount) || 0;
  el.textContent = t('selectedCount', n);
}
